"""Data contracts and Pydantic schemas for the RAG platform.

Defines API request/response structures for document management and question answering.
"""

from typing import List, Optional
from pydantic import BaseModel, Field


class SourceCitation(BaseModel):
    """Citation pointing directly to the source chunk in a document."""
    document_id: str = Field(..., description="Unique ID of the parent document")
    filename: str = Field(..., description="Original name of the uploaded file")
    page: int = Field(..., description="1-indexed page number where passage is found")
    chunk_id: str = Field(..., description="Unique chunk identifier")
    relevance_score: Optional[float] = Field(None, description="Similarity or relevance score")


class DocumentInfo(BaseModel):
    """Metadata details for an ingested document."""
    document_id: str
    filename: str
    file_size_bytes: int
    total_pages: int
    total_chunks: int
    uploaded_at: str


class DocumentUploadResponse(BaseModel):
    """Response returned upon successful document upload and indexing."""
    success: bool = True
    message: str
    document: DocumentInfo


class DocumentListResponse(BaseModel):
    """List of all indexed documents in the system."""
    documents: List[DocumentInfo]
    total_count: int


class DocumentDeleteResponse(BaseModel):
    """Response returned when a document is deleted."""
    success: bool
    message: str
    document_id: str


class ChatRequest(BaseModel):
    """Query payload submitted by the user."""
    question: str = Field(..., min_length=2, max_length=1000, description="User's query")
    document_ids: Optional[List[str]] = Field(None, description="Optional filter to specific document IDs")
    top_k: Optional[int] = Field(default=4, ge=1, le=20, description="Number of chunks to retrieve")


class ChatResponse(BaseModel):
    """Context-grounded response generated by the RAG pipeline."""
    question: str
    answer: str
    sources: List[SourceCitation]
    grounded: bool = Field(..., description="True if evidence was found and answer is strictly grounded")


class HealthResponse(BaseModel):
    """Application health and status summary."""
    status: str
    app_name: str
    version: str
    embedding_provider: str
    llm_provider: str
    vector_store_ready: bool
